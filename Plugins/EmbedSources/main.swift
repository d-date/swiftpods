import Foundation

// Usage: EmbedSources <output.swift> <input.swift>...
// Writes the concatenated inputs as a Swift string literal.
let arguments = CommandLine.arguments.dropFirst()
guard let output = arguments.first else {
    FileHandle.standardError.write(Data("usage: EmbedSources <output> <inputs...>\n".utf8))
    exit(1)
}

var combined = ""
for input in arguments.dropFirst() {
    let url = URL(fileURLWithPath: input)
    combined += "// MARK: - \(url.lastPathComponent)\n"
    combined += try String(contentsOf: url, encoding: .utf8)
    combined += "\n"
}

let delimiter = "#####"
guard !combined.contains("\"\"\"" + delimiter) else {
    FileHandle.standardError.write(Data("error: sources contain the raw string delimiter\n".utf8))
    exit(1)
}

let generated = """
// Generated by EmbedSources. Do not edit.
package let embeddedDescriptionSources: String = \(delimiter)\"\"\"
\(combined)
\"\"\"\(delimiter)

"""
try generated.write(to: URL(fileURLWithPath: output), atomically: true, encoding: .utf8)
