import PodsCore
import PodsPodfile

/// Renders the Package.swift that distributes the binaries of a Podfile's `distribution` target.
struct DistributionManifest {
    /// A Swift package the `Common` target depends on.
    struct Dependency: Equatable, Sendable {
        let url: String
        let requirement: DistributionRequirement
        let products: [String]
    }

    /// Deterministic: the output depends only on the values passed in, never on dictionary or array order
    /// of `checksums` and `dependencies`. Products and their targets keep the order of `layout`.
    /// - Parameter checksums: binary target name to the SHA-256 of its zip; every binary target needs one.
    static func render(
        settings: DistributionSettings,
        version: String,
        platform: Platform,
        layout: DistributionLayout,
        checksums: [String: String],
        dependencies: [Dependency]
    ) -> String {
        let dependencies = dependencies.sorted { $0.url < $1.url }
        let baseURL = settings.url.hasSuffix("/") ? String(settings.url.dropLast()) : settings.url

        var lines = [
            "// swift-tools-version: 5.9",
            "// Generated by swiftpods. Do not edit by hand: the next run overwrites this file.",
            "",
            "import PackageDescription",
        ]
        for case .unsafe(_, _, let warning) in dependencies.map(\.requirement) {
            lines.append("#warning(\(literal(warning)))")
        }
        lines += [
            "",
            "let package = Package(",
            "  name: \(literal(settings.name)),",
            "  platforms: [.\(platform.name.displayName)(\(literal(platform.effectiveDeploymentTarget.description)))],",
            "  products: [",
        ]
        for product in layout.products {
            lines += [
                "    .library(",
                "      name: \(literal(product.name)),",
                "      targets: [\(product.targets.map(literal).joined(separator: ", "))]),",
            ]
        }
        lines += ["  ],", "  dependencies: ["]
        for dependency in dependencies {
            lines.append("    .package(url: \(literal(dependency.url)), \(requirement(dependency.requirement))),")
        }
        lines += ["  ],", "  targets: ["]
        for name in layout.binaryTargets {
            precondition(checksums[name] != nil, "No checksum for binary target \(name)")
            lines += [
                "    .binaryTarget(",
                "      name: \(literal(name)),",
                "      url: \(literal("\(baseURL)/releases/download/\(version)/\(name).xcframework.zip")),",
                "      checksum: \(literal(checksums[name] ?? ""))),",
            ]
        }
        let commonDependencies = layout.commonTargets.map(literal) + dependencies.flatMap { dependency in
            dependency.products.sorted().map { ".product(name: \(literal($0)), package: \(literal(identity(of: dependency.url))))" }
        }
        lines.append("    .target(")
        lines.append("      name: \"Common\",")
        lines.append("      dependencies: [")
        lines += commonDependencies.map { "        \($0)," }
        lines += ["      ]),", "  ]", ")", ""]
        return lines.joined(separator: "\n")
    }

    /// Sources/Common/export.swift: one `@_exported import <M>` per Common binary target, sorted.
    static func renderCommonExports(layout: DistributionLayout) -> String {
        layout.commonTargets.sorted().map { "@_exported import \($0)\n" }.joined()
    }

    private static func requirement(_ requirement: DistributionRequirement) -> String {
        switch requirement {
        case .exact(let version): "exact: \(literal(version.description))"
        case .closedRange(let lower, let upper): "\(literal(lower.description))...\(literal(upper.description))"
        case .unsafe(let lower, let upper, _): "\(literal(lower.description))..<\(literal(upper.description))"
        }
    }

    /// SwiftPM's package identity: last path component without `.git`, in the case of the URL.
    private static func identity(of url: String) -> String {
        var name = url.split(separator: "/").last.map(String.init) ?? url
        if name.hasSuffix(".git") { name.removeLast(4) }
        return name
    }

    /// A Swift string literal for `text`.
    private static func literal(_ text: String) -> String {
        var result = "\""
        for character in text.unicodeScalars {
            switch character {
            case "\\": result += "\\\\"
            case "\"": result += "\\\""
            case "\n": result += "\\n"
            case "\r": result += "\\r"
            case "\t": result += "\\t"
            default: result.unicodeScalars.append(character)
            }
        }
        return result + "\""
    }
}
